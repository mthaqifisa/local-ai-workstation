"""Colima VM + Docker UI containers (Open WebUI, SearXNG, Portainer).

- Colima: started with the registry's cpu/memory; resized if they drift (disk can only grow).
  Auto-start at login via ~/Library/LaunchAgents/com.law.colima.plist.
- Containers: each carries labels law.managed=1 and law.spec=<hash of its full spec>.
  Missing → created. Spec changed / created by v1 → recreated. Stopped → started.
  law-managed containers no longer in the registry → removed. v1 Langfuse containers → removed.
  Named volumes are NEVER removed (Open WebUI chats, Portainer data).
"""
from __future__ import annotations

import hashlib
import json
import secrets

from ..engine import Action, Ctx, Step
from ..registry import load
from ..util import atomic_write, merge_env, read_env, which

COLIMA_LABEL = "com.law.colima"


# ── Colima ──────────────────────────────────────────────────────────────
def _colima_plist() -> str:
    colima = which("colima") or "/opt/homebrew/bin/colima"
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>{COLIMA_LABEL}</string>
  <key>ProgramArguments</key><array><string>{colima}</string><string>start</string></array>
  <key>EnvironmentVariables</key><dict>
    <key>PATH</key><string>/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin</string>
  </dict>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><false/>
</dict></plist>
"""


def plan_colima(ctx: Ctx) -> list[Action]:
    c = load(ctx.paths).docker.get("colima", {})
    cpu, mem, disk = int(c.get("cpu", 4)), int(c.get("memory_gb", 4)), int(c.get("disk_gb", 60))
    acts: list[Action] = []
    info = ctx.sys.colima_info()
    if info is None or info["status"].lower() != "running":
        acts.append(Action("add", f"start Colima ({cpu} CPU, {mem} GB RAM)",
                           lambda: ctx.sys.colima_start(cpu, mem, max(disk, (info or {}).get("disk_gb", 0)))))
    elif info["cpus"] != cpu or info["memory_gb"] != mem:
        def resize():
            ctx.sys.colima_stop()
            ctx.sys.colima_start(cpu, mem, max(disk, info["disk_gb"]))
        acts.append(Action("update", f"resize Colima {info['cpus']} CPU/{info['memory_gb']} GB → "
                                     f"{cpu} CPU/{mem} GB", resize))
    plist = ctx.paths.launch_agents / f"{COLIMA_LABEL}.plist"
    body = _colima_plist()
    if not plist.exists() or plist.read_text() != body:
        acts.append(Action("add", f"auto-start Colima at login ({plist.name})",
                           lambda: atomic_write(plist, body)))
    return acts


# ── SearXNG settings (secret generated once, kept in .env) ──────────────
def _searxng_settings(ctx: Ctx) -> str:
    secret = read_env(ctx.paths.env_file).get("SEARXNG_SECRET", "")
    return f"""# generated by law — edit registry.yaml / law code instead
use_default_settings: true
server:
  secret_key: "{secret}"
  limiter: false
  image_proxy: false
search:
  formats: [html, json]
"""


def _ensure_secret(ctx: Ctx) -> None:
    merge_env(ctx.paths.env_file, {"SEARXNG_SECRET": secrets.token_hex(32)})


# ── containers ──────────────────────────────────────────────────────────
def desired(ctx: Ctx) -> dict[str, list[str]]:
    reg = load(ctx.paths)
    ports = reg.ports
    fill = lambda s: s.format(law=str(ctx.paths.law), **ports)
    res: dict[str, list[str]] = {}
    for name, c in (reg.docker.get("containers") or {}).items():
        args = ["--name", name, "--restart", "unless-stopped",
                "--add-host", "host.docker.internal:host-gateway",
                "-p", f"{reg.bind_host}:{ports[c['port']]}:{c['container_port']}"]
        for v in c.get("volumes", []):
            args += ["-v", fill(v)]
        for k, v in sorted((c.get("env") or {}).items()):
            args += ["-e", f"{k}={fill(str(v))}"]
        extra = _searxng_settings(ctx) if name == "searxng" else ""
        spec = hashlib.sha256(json.dumps([args, c["image"], extra]).encode()).hexdigest()[:16]
        res[name] = args + ["--label", "law.managed=1", "--label", f"law.spec={spec}", c["image"]]
    return res


def _spec_of(args: list[str]) -> str:
    return next(a.split("=", 1)[1] for a in args if a.startswith("law.spec="))


def plan_containers(ctx: Ctx) -> list[Action]:
    acts: list[Action] = []
    if not read_env(ctx.paths.env_file).get("SEARXNG_SECRET"):
        acts.append(Action("add", "SearXNG secret key", lambda: _ensure_secret(ctx)))
        return acts                                   # re-plan after the secret exists
    sx = ctx.paths.searxng / "settings.yml"
    body = _searxng_settings(ctx)
    if not sx.exists() or sx.read_text() != body:
        acts.append(Action("update" if sx.exists() else "add", "SearXNG settings.yml",
                           lambda: atomic_write(sx, body)))

    if not ctx.sys.docker_ok():
        raise RuntimeError("Docker is not reachable — Colima did not start. Try: colima start")
    want = desired(ctx)
    have = {c["name"]: c for c in ctx.sys.docker_containers()}
    for name, args in want.items():
        image = args[-1]
        cur = have.get(name)
        if cur is None:
            def create(args=args, image=image):
                ctx.sys.docker_pull(image); ctx.sys.docker_run(args)
            acts.append(Action("add", f"container {name}", create))
        elif cur["labels"].get("law.spec") != _spec_of(args) or (ctx.upgrade and name not in ctx.upgraded):
            why = "from v1" if "law.managed" not in cur["labels"] else ("upgrade" if ctx.upgrade else "spec changed")
            def recreate(name=name, args=args, image=image):
                ctx.sys.docker_pull(image); ctx.sys.docker_rm(name); ctx.sys.docker_run(args)
                ctx.upgraded.add(name)
            acts.append(Action("update", f"container {name} ({why}; volumes kept)", recreate))
        elif cur["state"] != "running":
            acts.append(Action("update", f"start container {name}", lambda n=name: ctx.sys.docker_start(n)))
    for name, cur in have.items():
        lab = cur["labels"]
        if (lab.get("law.managed") == "1" and name not in want) or \
           lab.get("com.docker.compose.project") == "langfuse":
            acts.append(Action("remove", f"container {name} (no longer needed; volumes kept)",
                               lambda n=name: ctx.sys.docker_rm(n)))
    return acts


STEPS = [
    Step("colima", "Docker VM (Colima)", plan_colima, macos_only=True),
    Step("containers", "Web UIs: Open WebUI, SearXNG, Portainer", plan_containers, macos_only=True),
]
