class OpenWebUIState:
    """Restore the repo's saved Open WebUI items (settings/openwebui, written by `law save`). Only adds what is
    missing, and only re-runs when the saved files change."""

    name = "openwebui-state"

    def __init__(self, c: Ctx) -> None:
        self.c = c
        self.folder = c.paths.repo / "settings" / "openwebui"
        self.stamp = c.paths.state / "openwebui-state.stamp"

    def _digest(self) -> str:
        files = sorted(self.folder.glob("*.json")) if self.folder.is_dir() else []
        return hashlib.sha256(b"".join(f.name.encode() + f.read_bytes() for f in files)).hexdigest()

    def plan(self) -> list[str]:
        if not self.folder.is_dir() or not any(self.folder.glob("*.json")):
            return []
        current = self.stamp.read_text().strip() if self.stamp.exists() else ""
        return [] if current == self._digest() else ["restore saved Open WebUI presets, prompts and knowledge"]

    def apply(self) -> None:
        from law.state_sync import OpenWebUI, load
        if not wait_port(self.c.reg.ports.open_webui, 240):
            raise RuntimeError("Open WebUI is not listening")
        OpenWebUI(f"http://127.0.0.1:{self.c.reg.ports.open_webui}").restore(load(self.folder))
        self.stamp.parent.mkdir(parents=True, exist_ok=True)
        self.stamp.write_text(self._digest() + "\n")

    def verify(self) -> list[str]:
        return self.plan()


class DocTools:
    """The headless browser mermaid-cli renders diagrams with (for /proposal PDFs). Homebrew's mermaid-cli does not
    download one; this installs the exact chrome-headless-shell its puppeteer pins into ~/LAW/runtime/chrome and
    writes ~/LAW/config/puppeteer.json for `mmdc -p`."""

    name = "doc-tools"
    URL = "https://storage.googleapis.com/chrome-for-testing-public/{v}/mac-arm64/chrome-headless-shell-mac-arm64.zip"

    def __init__(self, c: Ctx) -> None:
        self.c = c
        self.root = c.paths.runtime / "chrome"
        self.config = c.paths.config / "puppeteer.json"

    def _version(self) -> str | None:
        """The browser version mermaid-cli's puppeteer expects, read from its pinned revisions."""
        mmdc = shutil.which("mmdc")
        if not mmdc:
            return None
        # `mmdc` links into the package (…/@mermaid-js/mermaid-cli/src/cli.js); walk up to the folder that holds
        # its own puppeteer-core.
        rel = Path("node_modules") / "puppeteer-core" / "lib" / "puppeteer" / "revisions.js"
        rev = next((d / rel for d in Path(mmdc).resolve().parents if (d / rel).exists()), None)
        if rev is None:
            return None
        m = re.search(r"'chrome-headless-shell':\s*'([\d.]+)'", rev.read_text())
        return m.group(1) if m else None

    def _exe(self, version: str) -> Path:
        return self.root / version / "chrome-headless-shell-mac-arm64" / "chrome-headless-shell"

    def plan(self) -> list[str]:
        version = self._version()
        if version is None:
            return []  # mermaid-cli comes with the brew step; nothing to pair it with yet
        want = json.dumps({"executablePath": str(self._exe(version))})
        ok = self._exe(version).exists() and self.config.exists() and self.config.read_text().strip() == want
        return [] if ok else [f"install chrome-headless-shell {version} for diagram rendering"]

    def apply(self) -> None:
        version = self._version()
        if version is None:
            return
        dest = self.root / version
        if not self._exe(version).exists():
            dest.mkdir(parents=True, exist_ok=True)
            archive = dest / "shell.zip"
            for cmd in (["curl", "-fsSL", "-o", str(archive), self.URL.format(v=version)],
                        ["ditto", "-x", "-k", str(archive), str(dest)]):
                res = self.c.sys.run(cmd, timeout=900)
                if not res.ok:
                    raise RuntimeError(res.out[-1500:])
            archive.unlink(missing_ok=True)
        for old in self.root.iterdir():  # keep only the version in use
            if old.is_dir() and old.name != version:
                shutil.rmtree(old)
        self.config.parent.mkdir(parents=True, exist_ok=True)
        self.config.write_text(json.dumps({"executablePath": str(self._exe(version))}) + "\n")

    def verify(self) -> list[str]:
        return self.plan()


class ApiTools:
    """The pinned TypeScript compiler `law api` reads .d.ts files with. TypeScript 7 (the native compiler) has no
    JavaScript compiler API, so projects on it cannot lend theirs; this one is used whenever theirs is 7 or newer."""

    name = "api-tools"
    TYPESCRIPT = "6.0.3"

    def __init__(self, c: Ctx) -> None:
        self.c = c
        self.root = c.paths.runtime / "api-tools"

    def _installed(self) -> str | None:
        manifest = self.root / "node_modules" / "typescript" / "package.json"
        return str(json.loads(manifest.read_text()).get("version")) if manifest.exists() else None

    def plan(self) -> list[str]:
        return [] if self._installed() == self.TYPESCRIPT else [f"install typescript {self.TYPESCRIPT} for law api"]

    def apply(self) -> None:
        self.root.mkdir(parents=True, exist_ok=True)
        manifest = {"name": "law-api-tools", "private": True, "dependencies": {"typescript": self.TYPESCRIPT}}
        (self.root / "package.json").write_text(json.dumps(manifest, indent=2) + "\n")
        res = self.c.sys.run(["npm", "install", "--prefix", str(self.root), "--no-audit", "--no-fund"], timeout=900)
        if not res.ok:
            raise RuntimeError(res.out[-1500:])

    def verify(self) -> list[str]:
        return self.plan()


