class Models:
    """LLM weights in ~/LAW/models/llm/<id>, pinned by revision; a marker proves completeness."""

    name = "models"

    def __init__(self, c: Ctx) -> None:
        self.c = c

    def _models(self) -> list[tuple[str, str, str]]:
        return [(m.id, m.repo, m.revision) for m in self.c.reg.llm_models
                if self.c.profile == "full" or m.lane == "light"]

    def _marker(self, model_id: str) -> Path:
        return self.c.paths.llm_models / model_id / ".law-complete"

    def plan(self) -> list[str]:
        out = []
        for mid, repo, rev in self._models():
            mk = self._marker(mid)
            if not mk.exists() or mk.read_text().strip() != rev:
                out.append(f"download {repo}@{rev[:8]} -> {mid}")
        return out

    def apply(self) -> None:
        hf = str(self.c.paths.runtime / "bin" / "hf")  # installed by the media-tools step
        for mid, repo, rev in self._models():
            mk = self._marker(mid)
            if mk.exists() and mk.read_text().strip() == rev:
                continue
            dest = self.c.paths.llm_models / mid
            res = self.c.sys.run([hf, "download", repo, "--revision", rev, "--local-dir", str(dest)],
                                 env={"HF_HOME": str(self.c.paths.models / "hf")}, timeout=6 * 3600)
            if not res.ok:
                raise RuntimeError(f"download {repo} failed: {res.out[-1000:]}")
            if not any(dest.glob("*.safetensors")):
                raise RuntimeError(f"{repo}: no weights after download")
            mk.write_text(rev + "\n")

    def verify(self) -> list[str]:
        return self.plan()


def _uv_env(paths: LawPaths) -> dict[str, str]:
    return {"UV_TOOL_DIR": str(paths.runtime / "tools"), "UV_TOOL_BIN_DIR": str(paths.runtime / "bin"),
            "UV_CACHE_DIR": str(paths.cache / "uv"), "UV_PYTHON_INSTALL_DIR": str(paths.runtime / "python")}


WORKER_RESTART_FLAG = "worker-restart.pending"


def jobs_running(reg: Registry) -> int:
    """How many jobs the worker is running now (0 if the queue store is unreachable)."""
    import redis

    try:
        client = redis.Redis(host=reg.network.loopback, port=reg.ports.valkey, socket_timeout=3)
        return int(client.zcard("law:running"))
    except redis.RedisError:
        return 0


class Services:
    """launchd agents for valkey, oMLX, Caddy, API, worker, Telegram."""

    name = "services"

    def __init__(self, c: Ctx) -> None:
        self.c = c

    def agents(self) -> list[launchd.Agent]:
        p, reg = self.c.paths, self.c.reg
        venv_bin = p.runtime / "law-venv" / "bin"
        env_common = {"HF_HOME": str(p.models / "hf"), "OPENCODE_CONFIG": str(p.config / "opencode.json"),
                      "TMPDIR": str(p.tmp)}
        caddyfile = p.config / "Caddyfile"
        agents = [
            launchd.Agent(reg.services["valkey"].label or "com.law6.valkey", [
                "/opt/homebrew/bin/valkey-server", "--bind", reg.network.loopback,
                "--port", str(reg.ports.valkey), "--dir", str(p.data / "valkey"), "--appendonly", "yes",
                "--appendfsync", "everysec", "--save", "300 1", "--protected-mode", "yes"]),
            launchd.Agent(reg.services["omlx"].label or "com.law6.omlx", [
                "/opt/homebrew/bin/omlx", "serve", "--model-dir", str(p.llm_models), "--host",
                reg.network.loopback, "--port", str(reg.ports.llm_internal), "--headless",
                "--memory-guard-gb", str(reg.machine.model_budget_gb),
                "--base-path", str(p.runtime / "omlx")],
                # oMLX discovers models only at start: changing the model set must restart it.
                env={**env_common, "LAW_MODELS": ",".join(sorted(m.id for m in reg.llm_models))}),
            launchd.Agent(reg.services["caddy"].label or "com.law6.caddy", [
                "/opt/homebrew/bin/caddy", "run", "--config", str(caddyfile), "--adapter", "caddyfile"]),
            launchd.Agent(reg.services["api"].label or "com.law6.api", [str(venv_bin / "law"), "serve"],
                          env=env_common, reads_registry=True),
            launchd.Agent(reg.services["worker"].label or "com.law6.worker", [str(venv_bin / "law"), "worker"],
                          env=env_common, reads_registry=True),
        ]
        values = secrets.read(p.env_file)
        if values.get("LAW_TELEGRAM_TOKEN"):
            agents.append(launchd.Agent(reg.services["telegram"].label or "com.law6.telegram",
                                        [str(venv_bin / "law"), "telegram"], env=env_common,
                                        reads_registry=True))
        return agents

    def caddyfile(self) -> str:
        reg = self.c.reg
        return (
            "{\n\tadmin off\n\tauto_https off\n}\n\n"
            f"http://:{reg.ports.llm_public} {{\n"
            f"\tbind {reg.network.bind}\n"
            f"\treverse_proxy {reg.network.loopback}:{reg.ports.llm_internal} {{\n"
            "\t\tflush_interval -1\n"
            "\t\ttransport http {\n\t\t\tresponse_header_timeout 3600s\n\t\t\tread_timeout 3600s\n\t\t}\n"
            "\t}\n}\n"
        )

    def plan(self) -> list[str]:
        out = []
        cf = self.c.paths.config / "Caddyfile"
        if not cf.exists() or cf.read_text() != self.caddyfile():
            out.append(f"write {cf}")
        for agent in self.agents():
            if launchd.needs_update(self.c.paths, agent, self.c.stamp):
                out.append(f"install launchd agent {agent.label}")
            elif not self.c.sys.launchd_loaded(agent.label):
                out.append(f"load launchd agent {agent.label}")
        return out

    def apply(self) -> None:
        cf = self.c.paths.config / "Caddyfile"
        cf.write_text(self.caddyfile())
        worker = self.c.reg.services["worker"].label or "com.law6.worker"
        for agent in self.agents():
            if agent.label == worker and self._defer_worker(agent):
                continue
            launchd.apply(self.c.paths, agent, self.c.stamp, self.c.sys)
            record_owned(self.c.paths, "launchd", agent.label)

    def _defer_worker(self, agent: launchd.Agent) -> bool:
        """Never restart the worker in the middle of an agent step. With jobs running, a code-only change is
        written and the worker restarts itself between steps (it watches WORKER_RESTART_FLAG); any other change
        waits for the next `law install` when idle. LAW_FORCE_RESTART=1 restarts at once."""
        if os.environ.get("LAW_FORCE_RESTART") == "1" or not launchd.needs_update(self.c.paths, agent, self.c.stamp):
            return False
        running = jobs_running(self.c.reg)
        if not running:
            return False
        plist = launchd.plist_path(self.c.paths, agent.label)
        current = plist.read_bytes() if plist.exists() else b""
        old_stamp = launchd.stamp_of(current)
        if old_stamp is not None and agent.render(self.c.paths, old_stamp) == current:
            plist.write_bytes(agent.render(self.c.paths, self.c.stamp))
            self.c.paths.state.mkdir(parents=True, exist_ok=True)
            (self.c.paths.state / WORKER_RESTART_FLAG).write_text(self.c.stamp + "\n")
            print(f"  worker: {running} job step(s) running; it restarts on the new code between steps")
        else:
            print(f"  worker: update postponed while {running} job step(s) run; run `law install` again when idle "
                  "(or LAW_FORCE_RESTART=1)")
        return True

    def verify(self) -> list[str]:
        reg = self.c.reg
        problems = [f"{a.label} not loaded" for a in self.agents() if not self.c.sys.launchd_loaded(a.label)]
        for name, port, wait in (("valkey", reg.ports.valkey, 20), ("omlx", reg.ports.llm_internal, 120),
                                 ("caddy", reg.ports.llm_public, 20), ("api", reg.ports.law_api, 60)):
            if not wait_port(port, wait):
                problems.append(f"{name} not listening on :{port}")
        return problems


class MediaModels:
    """Pre-download media model repos into the shared HF cache at pinned revisions (fast, resumable)."""

    name = "media-models"

    def __init__(self, c: Ctx) -> None:
        self.c = c

    def _wanted(self) -> list[tuple[str, str]]:
        if self.c.profile != "full":
            return []
        seen: dict[str, str] = {}
        for m in self.c.reg.media.values():
            if m.prefetch and m.hf_revision:
                seen[m.hf_repo or m.model] = m.hf_revision
            if m.prefetch:
                for extra in m.hf_extra:
                    repo, _, rev = extra.partition("@")
                    if rev:
                        seen[repo] = rev
        return sorted(seen.items())

    def _wanted_files(self) -> list[tuple[str, str, str]]:
        """Single files from big repos (LoRA adapters): (repo, revision, path)."""
        if self.c.profile != "full":
            return []
        out: set[tuple[str, str, str]] = set()
        for m in self.c.reg.media.values():
            for lora in (m.fast.loras if m.fast and m.prefetch else []):
                ref, path = lora.split(":", 1)
                repo, rev = ref.split("@", 1)
                out.add((repo, rev, path))
        return sorted(out)

    def _marker(self, repo: str, path: str = "") -> Path:
        name = repo.replace("/", "--") + (("--" + path.replace("/", "--")) if path else "")
        return self.c.paths.state / "prefetch" / f"{name}.rev"

    def _done(self, mk: Path, rev: str) -> bool:
        return mk.exists() and mk.read_text().strip() == rev

    def plan(self) -> list[str]:
        repos = [f"download {repo}@{rev[:8]}" for repo, rev in self._wanted()
                 if not self._done(self._marker(repo), rev)]
        files = [f"download {repo}@{rev[:8]}:{path}" for repo, rev, path in self._wanted_files()
                 if not self._done(self._marker(repo, path), rev)]
        return repos + files

    def apply(self) -> None:
        hf = str(self.c.paths.runtime / "bin" / "hf")
        jobs = [(repo, rev, None) for repo, rev in self._wanted()] + list(self._wanted_files())
        for repo, rev, path in jobs:
            mk = self._marker(repo, path or "")
            if self._done(mk, rev):
                continue
            cmd = [hf, "download", repo, *([path] if path else []), "--revision", rev]
            res = self.c.sys.run(cmd, env={"HF_HOME": str(self.c.paths.models / "hf")}, timeout=6 * 3600)
            if not res.ok:
                raise RuntimeError(f"download {repo} {path or ''} failed: {res.out[-1000:]}")
            mk.parent.mkdir(parents=True, exist_ok=True)
            mk.write_text(rev + "\n")

    def verify(self) -> list[str]:
        return self.plan()


def model_options(effort: str, sampling: Sampling | None = None) -> dict[str, Any]:
    """What OpenCode sends the model for a thinking level. "off" turns the Qwen chat template's thinking off
    (checked on the wire: OpenCode passes chat_template_kwargs through); reasoning_effort cannot (measured:
    'none' still thinks). With the model card's sampling, its top_p, top_k, min_p and presence penalty go along
    (the temperature is the agent's own field)."""
    extra = {k: v for k, v in sampling.body().items() if k != "temperature"} if sampling else {}
    if effort == "off":
        return {"chat_template_kwargs": {"enable_thinking": False}, **extra}
    return {"reasoningEffort": effort, **extra}


class OpenCodeConfig:
    """OpenCode provider + role agents pointed at the local LLM endpoint (full permissions)."""

    name = "opencode-config"

    def __init__(self, c: Ctx) -> None:
        self.c = c
        self.file = c.paths.config / "opencode.json"

    def render(self) -> str:
        reg = self.c.reg
        base = f"http://127.0.0.1:{reg.ports.llm_public}/v1"
        # `temperature: true` makes OpenCode send the agent's temperature at all (checked on the wire, OpenCode
        # 1.18.7: without it no temperature goes out and oMLX falls back to its own default)
        models = {m.id: {"name": m.id, "limit": {"context": m.context or 32768,
                                                 "output": output_limit(m.context, writes=set(m.roles) != {"judge"})},
                         **({"temperature": True} if m.sampling else {}),
                         # a vision model sees images (a design reference, a screenshot): without these OpenCode
                         # sends text only (checked on the wire; seen 2026-10-28, an agent probing an image's pixels
                         # with a Swift script because it could not see it)
                         **({"attachment": True, "modalities": {"input": ["text", "image"], "output": ["text"]}}
                            if m.vision else {})}
                  for m in reg.llm_models if m.lane == "heavy"}
        doc = {
            "$schema": "https://opencode.ai/config.json",
            "provider": {"law": {"npm": "@ai-sdk/openai-compatible", "name": "LAW local",
                                 "options": {"baseURL": base, "apiKey": "local"}, "models": models}},
            "model": f"law/{reg.model_for_role('coder').id}",
            "small_model": f"law/{reg.model_for_role('fast').id}",
            "permission": {"edit": "allow", "bash": "allow", "webfetch": "allow", "external_directory": "allow"},
            "mcp": {"mac": {"type": "local", "enabled": True,
                            "command": [str(self.c.paths.runtime / "law-venv" / "bin" / "law"), "mcp-mac"]}},
            "agent": self._agents(),
            "autoupdate": False,
            "share": "disabled",
        }
        return json.dumps(doc, indent=2) + "\n"

    def _agents(self) -> dict[str, Any]:
        """One OpenCode agent per role in settings/roles.yaml; tool access follows each role's `tools` list."""
        from law import roles as roles_mod

        roles = roles_mod.load(self.c.paths.settings / "roles.yaml")
        agents: dict[str, Any] = {}
        for name, role in roles.roles.items():
            tools = set(role.tools)
            model = self.c.reg.model_for_role(role.model_role)
            sampling = model.sampling_for(role.reasoning)
            agents[name] = {
                "description": role.summary,
                "mode": "primary",
                "model": f"law/{model.id}",
                "temperature": sampling.temperature if sampling else role.temperature,
                "prompt": roles.system_prompt(name),
                "tools": {
                    "write": "files" in tools, "edit": "files" in tools, "patch": "files" in tools,
                    "bash": bool(tools & {"shell", "mac"}),
                    "read": bool(tools & {"read", "files"}), "grep": True, "glob": True, "list": True,
                    "webfetch": bool(tools & {"search", "browser"}),
                    "mac_*": "mac" in tools,
                },
            }
        return agents

    def files(self) -> dict[Path, str]:
        """The shared config plus one per role. In a role's file the housekeeping `small_model` is the role's own
        model (OpenCode calls it for titles/summaries, and a second large model would not fit beside the first),
        and the model carries the role's reasoning effort."""
        from law import roles as roles_mod

        roles = roles_mod.load(self.c.paths.settings / "roles.yaml")
        out = {self.file: self.render()}
        doc = json.loads(self.render())
        for name, agent in doc["agent"].items():
            role_doc = {**doc, "model": agent["model"], "small_model": agent["model"]}
            # The role's thinking budget. Without it the agent's model thinks unbounded: measured 20-45 minutes
            # between tool calls with Qwen3.8 (2026-10-20). OpenCode sends it as `reasoning_effort`.
            # A project can ask for another level (its `thinking`), so each role also gets one file per level.
            model_id = agent["model"].removeprefix("law/")
            for effort, suffix in ((roles.get(name).reasoning, ""), ("off", "-off"), ("low", "-low"),
                                   ("medium", "-medium"), ("xhigh", "-xhigh")):
                provider = json.loads(json.dumps(doc["provider"]))
                sampling = self.c.reg.model(model_id).sampling_for(effort)
                provider["law"]["models"][model_id]["options"] = model_options(effort, sampling)
                level_agents = doc["agent"]
                if sampling:  # thinking on and off have different recommended temperatures
                    level_agents = {**doc["agent"], name: {**agent, "temperature": sampling.temperature}}
                body = {**role_doc, "provider": provider, "agent": level_agents}
                out[self.c.paths.config / f"opencode-{name}{suffix}.json"] = json.dumps(body, indent=2) + "\n"
        return out

    def plan(self) -> list[str]:
        return [f"write {p}" for p, body in self.files().items() if not p.exists() or p.read_text() != body]

    def apply(self) -> None:
        for p, body in self.files().items():
            p.write_text(body)

    def verify(self) -> list[str]:
        return self.plan()


JUDGE_OUTPUT = 6144


def output_limit(context: int | None, *, writes: bool = True) -> int:
    """Tokens one agent reply may produce: half the context, at most oMLX's 32K. A coder writes whole files in
    one reply; replies of 10K+ tokens came close to the old 16K cap (2026-10-21), and a cut-off reply is lost.
    A judge-only model writes a verdict, so its context goes to reading: with half of 32K reserved, a review of a
    28 KB proposal was compacted mid-way and lost its findings (2026-10-25)."""
    return min(32768, (context or 32768) // 2) if writes else min(JUDGE_OUTPUT, (context or 32768) // 2)


def lan_hostname(sysapi: SysAPI) -> str:
    """Bonjour name (<name>.local) so links work from every device on the network."""
    res = sysapi.run(["scutil", "--get", "LocalHostName"])
    return f"{res.out.strip()}.local" if res.ok and res.out.strip() else "localhost"


class Colima:
    """The Docker VM, kept alive by a launchd agent (colima start --foreground)."""

    name = "colima"

    def __init__(self, c: Ctx) -> None:
        self.c = c

    def agent(self) -> launchd.Agent:
        m = self.c.reg.machine.colima
        label = self.c.reg.services["colima"].label or "com.law6.colima"
        return launchd.Agent(label, [
            "/opt/homebrew/bin/colima", "start", "--foreground", "--cpus", str(m.cpus),
            "--memory", str(m.memory_gb), "--disk", str(m.disk_gb), "--vm-type", "vz",
            "--mount-type", "virtiofs"], env={"COLIMA_HOME": str(self.c.paths.home / "colima")})

    def _docker_ok(self) -> bool:
        return self.c.sys.run(["docker", "info"], env=self._env(), timeout=20).ok

    def _env(self) -> dict[str, str]:
        sock = self.c.paths.home / "colima" / "default" / "docker.sock"
        return {"DOCKER_HOST": f"unix://{sock}", "COLIMA_HOME": str(self.c.paths.home / "colima")}

    def _sock(self) -> str:
        return self._env()["DOCKER_HOST"]

    def _context_ok(self) -> bool:
        """The docker CLI's current context is `colima`, pointing at LAW's VM. `colima stop` on another Colima
        instance deletes this shared context (seen 2026-10-25), and then a plain `docker ...` fails."""
        try:
            current = json.loads((self.c.paths.user_home / ".docker" / "config.json").read_text()).get("currentContext")
        except (OSError, json.JSONDecodeError):
            current = None
        host = self.c.sys.run(["docker", "context", "inspect", "colima", "--format", "{{.Endpoints.docker.Host}}"],
                              timeout=20)
        return current == "colima" and host.ok and host.out.strip() == self._sock()

    def _fix_context(self) -> None:
        verb = "update" if self.c.sys.run(["docker", "context", "inspect", "colima"], timeout=20).ok else "create"
        self.c.sys.run(["docker", "context", verb, "colima", "--docker", f"host={self._sock()}"], timeout=20)
        self.c.sys.run(["docker", "context", "use", "colima"], timeout=20)

    def plan(self) -> list[str]:
        a = self.agent()
        if launchd.needs_update(self.c.paths, a, self.c.stamp):
            return [f"install launchd agent {a.label}"]
        if not self.c.sys.launchd_loaded(a.label):
            return [f"load launchd agent {a.label}"]
        if not self._docker_ok():
            return ["wait for Docker VM"]
        return [] if self._context_ok() else ["point the docker CLI at LAW's VM (context colima)"]

    def apply(self) -> None:
        a = self.agent()
        launchd.apply(self.c.paths, a, self.c.stamp, self.c.sys)
        record_owned(self.c.paths, "launchd", a.label)
        deadline = time.time() + 300
        while time.time() < deadline and not self._docker_ok():
            time.sleep(3)
        if not self._context_ok():
            self._fix_context()

    def verify(self) -> list[str]:
        if not self._docker_ok():
            return ["Docker VM not reachable"]
        return [] if self._context_ok() else ["docker context colima does not point at LAW's VM"]


