ZPROFILE_MARK = "# >>> LAW v6 >>>"
ZPROFILE_END = "# <<< LAW v6 <<<"


@dataclass
class Ctx:
    paths: LawPaths
    reg: Registry
    sys: SysAPI
    interactive: bool = False
    imported_secrets: dict[str, str] | None = None
    profile: str = "full"  # "small" = tiny test models (fresh-machine VM test)

    @property
    def stamp(self) -> str:
        """Changes when the registry, roles or LAW's own code change, so registry readers restart after `git pull`."""
        h = hashlib.sha256()
        sources = [self.paths.registry_file, self.paths.settings / "roles.yaml",
                   *sorted((self.paths.repo / "src" / "law").rglob("*.py"))]
        for f in sources:
            if f.exists():
                h.update(str(f.relative_to(self.paths.repo)).encode())
                h.update(f.read_bytes())
        return h.hexdigest()[:12]


def port_open(port: int, host: str = "127.0.0.1", timeout: float = 0.5) -> bool:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.settimeout(timeout)
        return s.connect_ex((host, port)) == 0


def wait_port(port: int, seconds: float) -> bool:
    deadline = time.time() + seconds
    while time.time() < deadline:
        if port_open(port):
            return True
        time.sleep(0.5)
    return False


